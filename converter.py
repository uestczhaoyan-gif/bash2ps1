class Translator:
    BLOCKED = {'case', 'esac', 'function', 'select', 'eval', 'exec',
               'sh', 'zsh', 'sudo', 'su', 'apt', 'apt-get', 'yum', 'dnf', 'pacman',
               'chmod', 'chown', 'ln', 'sed', 'awk', 'xargs', 'read', 'trap',
               'return', 'break', 'continue', 'exit', 'pushd', 'popd', 'alias', 'unalias'}
    NATIVE = {'git', 'python', 'python3', 'pip', 'pip3', 'node', 'npm', 'npx', 'docker',
              'go', 'cargo', 'rustc', 'cmake', 'dotnet', 'java', 'javac', 'ffmpeg', 'tar',
              'curl', 'wget', 'make', 'code'}
    def __init__(self, source_path: Path | None = None, bundle: dict[Path, str] | None = None,
                 active: set[Path] | None = None):
        self.issues: list[Issue] = []
        self.commands = 0
        self.dependencies: set[str] = set()
        self.export_names: dict[str, str] = {}
        self.source_path = source_path.resolve() if source_path else None
        self.bundle = bundle if bundle is not None else {}
        self.active = active if active is not None else set()
        self.loop_depth = 0

    def warn(self, line: int, message: str):
        issue = Issue(line, 'warning', message)
        if issue not in self.issues:
            self.issues.append(issue)

    def word(self, token: Token, expansion: bool = False) -> str:
        raw, i, quote = token.raw, 0, None
        chunks: list[str] = []
        literal: list[str] = []
        def flush():
            if literal:
                chunks.append(ps_quote(''.join(literal)))
                literal.clear()
        if raw.startswith('~'):
            if raw == '~' or raw.startswith('~/'):
                chunks.append("(Get-B2PSValue 'HOME')")
                i = 1
            else:
                raise Unsupported('不支持 ~用户名 路径；请使用明确的 Windows 路径。')
        while i < len(raw):
            c = raw[i]
            if c == '\\' and quote != "'":
                if raw.startswith('\\\r\n', i):
                    i += 3
                    continue
                n = raw[i + 1]
                if n == '\n':
                    i += 2
                    continue
                if quote == '"' and n not in '$`"\\':
                    literal.append('\\')
                    i += 1
                else:
                    literal.append(n)
                    i += 2
                continue
            if quote == "'":
                if c == "'":
                    quote = None
                else:
                    literal.append(c)
                i += 1
                continue
            if c in "'\"" and (quote is None or quote == c):
                quote = None if quote == c else c
                i += 1
                continue
            if c == '`' or raw.startswith('$(', i):
                if raw.startswith('$((', i):
                    raise Unsupported('算术展开暂不支持；请使用外部程序计算或改成普通变量。')
                end = expansion_end(raw, i)
                source = raw[i + (1 if c == '`' else 2):end - 1]
                flush()
                parser = ShellParser(lex(source, token.line))
                code = self.nodes(parser.parse())
                chunks.append('(Invoke-B2PSCapture {\n' + code + '\n})')
                if quote is None and not expansion:
                    self.warn(token.line, '未加引号的命令替换按单个字符串传递；需要 Bash 单词拆分时请加引号或改写。')
                i = end
                continue
            if c == '$':
                if i + 1 < len(raw) and raw[i + 1] in "'\"":
                    raise Unsupported('ANSI-C / 本地化引号暂不支持。')
                if raw.startswith('${', i):
                    end = expansion_end(raw, i)
                    inner = raw[i + 2:end - 1]
                    if inner == 'BASH_SOURCE[0]':
                        inner = 'BASH_SOURCE'
                    match = re.fullmatch(r'([A-Za-z_][A-Za-z_0-9]*|\d+|[?#])(:?[-+=?])?(.*)', inner, re.S)
                    if not match or (not match[2] and match[3]):
                        raise Unsupported('该参数展开尚不支持；支持 ${NAME}、默认值、赋默认值、替代值和必填检查。')
                    flush()
                    if match[2]:
                        value = self.word(Token(match[3], token.line), expansion=True)
                        chunks.append(f'(Expand-B2PSParameter {ps_quote(match[1])} {ps_quote(match[2])} {{ {value} }})')
                    else:
                        chunks.append(f'(Get-B2PSValue {ps_quote(match[1])})')
                    i = end
                    continue
                match = re.match(r'\$([A-Za-z_][A-Za-z_0-9]*|[0-9?#])', raw[i:])
                if match:
                    name = match.group(1)
                    flush()
                    chunks.append(f'(Get-B2PSValue {ps_quote(name)})')
                    if quote is None and not expansion:
                        self.warn(token.line, '未加引号的变量按单个字符串传递；Bash 的单词拆分和通配符展开需人工检查。')
                    i += len(match.group(0))
                    continue
                if i + 1 < len(raw) and (raw[i + 1].isdigit() or raw[i + 1] in '{@*#!-'):
                    raise Unsupported('复杂参数展开或位置参数暂不支持；请先改成普通变量。')
            if not expansion and quote is None and c in '*?[]{}':
                raise Unsupported('未加引号的通配符或花括号展开需人工改写，避免误处理文件。')
            literal.append(c)
            i += 1
        flush()
        if not chunks:
            return "''"
        return chunks[0] if len(chunks) == 1 else '(' + ' + '.join(chunks) + ')'

    def literal(self, token: Token) -> str:
        raw, i, quote, value = token.raw, 0, None, []
        while i < len(raw):
            c = raw[i]
            if quote == "'":
                if c == "'":
                    quote = None
                else:
                    value.append(c)
            elif c in "'\"" and (quote is None or quote == c):
                quote = None if quote == c else c
            elif c == '\\':
                if i + 1 == len(raw):
                    raise Unsupported('末尾反斜杠缺少内容。')
                n = raw[i + 1]
                if n == '\n':
                    i += 1
                elif quote == '"' and n not in '$`"\\':
                    value.append(c)
                else:
                    value.append(n)
                    i += 1
            elif c in '$`' or (quote is None and c in '*?[]{}~'):
                raise Unsupported('命令名或选项需要是固定文本。')
            else:
                value.append(c)
            i += 1
        return ''.join(value)

    def paths(self, tokens: list[Token]) -> str:
        if not tokens:
            raise Unsupported('缺少路径参数。')
        return '@(' + ', '.join(self.word(t) for t in tokens) + ')'

    def options(self, tokens: list[Token], allowed: set[str]) -> tuple[set[str], list[Token]]:
        options, values, ended = set(), [], False
        for token in tokens:
            try:
                candidate = self.literal(token)
            except Unsupported:
                candidate = None
            if not ended and candidate == '--':
                ended = True
                continue
            if not ended and candidate and candidate.startswith('-') and candidate != '-':
                flag = candidate
                if flag.startswith('--'):
                    if flag not in allowed:
                        raise Unsupported(f'不支持选项 {flag}。')
                    options.add(flag)
                else:
                    for c in flag[1:]:
                        if '-' + c not in allowed:
                            raise Unsupported(f'不支持选项 -{c}。')
                        options.add('-' + c)
            else:
                values.append(token)
        return options, values

    def command(self, tokens: list[Token], in_pipeline: bool = False) -> str:
        if not tokens:
            raise Unsupported('缺少命令。')
        if any(t.kind != 'word' for t in tokens):
            raise Unsupported('暂不支持该 Bash 操作符（后台、子 Shell、输入/错误重定向或 here-document）。')
        assignments: list[tuple[str, Token]] = []
        while tokens and (match := re.match(r'^([A-Za-z_][A-Za-z_0-9]*)=(.*)$', tokens[0].raw, re.S)):
            assignments.append((match.group(1), Token(match.group(2), tokens[0].line)))
            tokens = tokens[1:]
        if assignments:
            if in_pipeline:
                raise Unsupported('管道中的变量赋值暂不支持。')
            if not tokens:
                return '; '.join(self.assignment(n, v) for n, v in assignments)
            code = self.command(tokens)
            if any(re.search(r'(?<!\\)\$', t.raw) for t in tokens):
                raise Unsupported('临时环境变量命令同时引用变量时，展开顺序需人工改写。')
            if len({n.lower() for n, _ in assignments}) != len(assignments):
                raise Unsupported('临时环境变量名称重复或大小写冲突。')
            saved, changes, restore = [], [], []
            for number, (name, value) in enumerate(assignments):
                if name.upper() == 'PATH':
                    raise Unsupported('临时 PATH 赋值需按 Windows 路径和分号分隔符人工改写。')
                key = ps_quote(name)
                saved.append(f"$b2psSaved{number} = [Environment]::GetEnvironmentVariable({key}, 'Process')")
                changes.append(f"[Environment]::SetEnvironmentVariable({key}, {self.word(value)}, 'Process')")
                restore.append(f"[Environment]::SetEnvironmentVariable({key}, $b2psSaved{number}, 'Process')")
            self.warn(tokens[0].line, '命令前的临时变量会仅在该命令期间写入进程环境，然后恢复。')
            return '; '.join(saved) + '; try { ' + '; '.join(changes) + '; ' + code + ' } finally { ' + '; '.join(restore) + ' }'
        dynamic = False
        try:
            name = tokens[0].raw if tokens[0].raw in {'[', '[[', ']]', '{', '}'} else self.literal(tokens[0])
        except Unsupported:
            name = ''
            dynamic = True
            name_expression = self.word(tokens[0])
        args = tokens[1:]
        if in_pipeline and name not in {'echo', 'printf', 'cat', 'grep', 'head', 'tail', 'wc', 'find', 'date', 'pwd', 'dirname', 'basename'}:
            raise Unsupported('管道支持已转换的文本命令；外部程序的二进制管道需人工检查。')
        if name in self.BLOCKED or name in {'{', '}', '[[', ']]', '!'}:
            raise Unsupported(f'{name} 依赖 Bash 控制结构或 Unix 工具，需要人工改写。')
        if name == 'export':
            if not args:
                raise Unsupported('export 需要变量名或赋值。')
            values = []
            for arg in args:
                match = re.fullmatch(r'([A-Za-z_][A-Za-z_0-9]*)(?:=(.*))?', arg.raw, re.S)
                if not match:
                    raise Unsupported('export 只支持普通变量名或 NAME=value。')
                variable, value = match.groups()
                values.append(self.assignment(variable, Token(value if value is not None else '"${' + variable + '}"', arg.line), True))
            return '; '.join(values)
        if name == 'unset':
            if not args or any(not re.fullmatch('[A-Za-z_][A-Za-z_0-9]*', t.raw) for t in args):
                raise Unsupported('unset 只支持普通变量名。')
            return '; '.join(f"$null = $script:B2PSVars.Remove({ps_quote(t.raw)}); $null = $script:B2PSExported.Remove({ps_quote(t.raw)}); [Environment]::SetEnvironmentVariable({ps_quote(t.raw)}, $null, 'Process')" for t in args)
        if name == 'set':
            values = []
            index = 0
            while index < len(args):
                arg = args[index]
                if arg.raw in {'-o', '+o'} or re.fullmatch(r'[-+][eua]*o', arg.raw):
                    if index + 1 >= len(args) or args[index + 1].raw != 'pipefail':
                        raise Unsupported('set -o / +o 目前支持 pipefail。')
                    values.append(f"$script:B2PSPipefail = ${'true' if arg.raw[0] == '-' else 'false'}")
                    index += 1
                    arg = Token(arg.raw[:-1], arg.line)
                if arg.raw not in {'-', '+'} and not re.fullmatch('[-+][eua]+', arg.raw):
                    raise Unsupported('set 支持 -e/-u/-a、对应 + 选项以及 -o/+o pipefail。')
                for c in arg.raw[1:]:
                    flag = {'e': 'Errexit', 'u': 'Unset', 'a': 'AllExport'}[c]
                    values.append(f"$script:B2PS{flag} = ${'true' if arg.raw[0] == '-' else 'false'}")
                index += 1
            if not values:
                raise Unsupported('不支持无参数的 set。')
            return '; '.join(values)
        if name in {'true', ':'}:
            return '$null = @(' + ', '.join(self.word(t) for t in args) + ')'
        if name == 'false' and not args:
            return 'Assert-B2PSTest $false'
        if name in {'test', '['}:
            if name == '[':
                if not args or args[-1].raw != ']':
                    raise Unsupported('[ 条件缺少 ]。')
                args = args[:-1]
            return 'Assert-B2PSTest (' + self.condition(args) + ')'
        if name == 'echo':
            if args and re.fullmatch(r'-[neE]+', args[0].raw):
                raise Unsupported('echo 的 -n/-e/-E 选项需人工改写。')
            return "Write-Output ((@(" + ', '.join(self.word(t) for t in args) + ")) -join ' ')"
        if name == 'printf':
            expression = self.printf_expression(args)
            return 'ConvertTo-B2PSLines -Text (' + expression + ')'
        if name == 'sleep':
            if len(args) != 1:
                raise Unsupported('sleep 支持一个秒数参数。')
            return 'Start-Sleep -Milliseconds ([int](1000 * [double]::Parse(' + self.word(args[0]) + ', [Globalization.CultureInfo]::InvariantCulture)))'
        if name in {'dirname', 'basename'}:
            if len(args) != 1:
                raise Unsupported(f'{name} 目前支持一个路径参数。')
            value = self.word(args[0])
            if name == 'dirname':
                return f"$b2psParent = [IO.Path]::GetDirectoryName(([string]{value}).TrimEnd([char[]]'/\\')); if ($b2psParent) {{ $b2psParent }} else {{ '.' }}"
            return f"[IO.Path]::GetFileName(([string]{value}).TrimEnd([char[]]'/\\'))"
        if name == 'date':
            utc = any(t.raw in {'-u', '--utc'} for t in args)
            rest = [t for t in args if t.raw not in {'-u', '--utc'}]
            if len(rest) > 1:
                raise Unsupported('date 支持 -Is、--iso-8601=seconds、-u 和常见 +格式。')
            fmt = self.literal(rest[0]) if rest else ''
            if fmt not in {'', '-Is', '--iso-8601=seconds'} and (not fmt.startswith('+') or re.search(r'%(?![YmdHMSFTszZ%])', fmt)):
                raise Unsupported('date 格式目前支持 %Y/%m/%d/%H/%M/%S/%F/%T/%s/%z/%%。')
            return 'Get-B2PSDate ' + ps_quote(fmt) + (' -Utc' if utc else '')
        if name == 'find':
            return self.find_command(args)
        if name in {'.', 'source', 'bash'}:
            return self.script_command(name, args, tokens[0].line)
        if name == 'pwd' and not args:
            return '(Get-Location).Path'
        if name == 'cd':
            if len(args) > 1 or (args and args[0].raw.startswith('-')):
                raise Unsupported('cd 只支持一个普通路径；cd - 需人工改写。')
            path = self.word(args[0]) if args else "(Get-B2PSValue 'HOME')"
            return 'Set-Location -LiteralPath ' + path
        if name == 'mkdir':
            flags, paths = self.options(args, {'-p', '--parents'})
            values = self.paths(paths)
            return (f'foreach ($b2psPath in {values}) {{ '
                    + ("if (Test-Path -LiteralPath $b2psPath -PathType Container) { continue }; " if flags else '')
                    + "New-Item -ItemType Directory -Path $b2psPath | Out-Null }")
        if name == 'touch':
            _, paths = self.options(args, set())
            return 'Update-B2PSFile -Paths ' + self.paths(paths)
        if name in {'cp', 'mv', 'rm'}:
            allowed = {'-r', '-R', '-f', '--recursive', '--force'} if name != 'mv' else {'-f', '--force'}
            flags, paths = self.options(args, allowed)
            force = ' -Force' if flags & {'-f', '--force'} else ''
            recurse = ' -Recurse' if flags & {'-r', '-R', '--recursive'} else ''
            if name == 'rm':
                values = self.paths(paths)
                self.warn(tokens[0].line, 'rm 会删除文件；运行前核对目标路径。')
                action = f'Remove-Item -LiteralPath $b2psPath{recurse}{force}'
                if force:
                    action = 'if (Test-Path -LiteralPath $b2psPath) { ' + action + ' }'
                return f'foreach ($b2psPath in {values}) {{ {action} }}'
            if len(paths) < 2:
                raise Unsupported(f'{name} 需要来源和目标路径。')
            if recurse:
                self.warn(tokens[0].line, '递归复制目录的覆盖和嵌套行为需检查目标目录。')
            self.warn(tokens[0].line, f'{name} 的已有目标目录和覆盖行为可能与 Unix 有差异，请核对。')
            command = 'Copy-Item' if name == 'cp' else 'Move-Item'
            return f'{command} -LiteralPath {self.paths(paths[:-1])} -Destination {self.word(paths[-1])}{recurse}{force}'
        if name == 'cat':
            if not args:
                raise Unsupported('cat 从标准输入读取需人工改写。')
            _, paths = self.options(args, set())
            self.warn(tokens[0].line, 'cat 按 UTF-8 文本行读取；二进制文件和字节完全一致的复制不适用。')
            return 'Get-Content -LiteralPath ' + self.paths(paths) + ' -Encoding UTF8'
        if name == 'ls':
            flags, paths = self.options(args, {'-a', '-A', '-l', '-h'})
            self.warn(tokens[0].line, 'ls 输出 PowerShell 文件对象，显示格式与 Bash 不同。')
            return 'Get-ChildItem' + (' -LiteralPath ' + self.paths(paths) if paths else '') + (' -Force' if flags & {'-a', '-A'} else '')
        if name == 'grep':
            flags, rest = self.options(args, {'-i', '-v', '-F', '-n'})
            if not rest:
                raise Unsupported('grep 缺少模式。')
            if '-n' in flags:
                raise Unsupported('grep -n 的文件/行号输出格式暂不支持。')
            if '-F' not in flags:
                self.warn(tokens[0].line, 'grep 使用 .NET 正则，复杂的 Bash BRE/ERE 模式需人工检查；固定文本建议 grep -F。')
            pattern = self.word(rest[0])
            if len(rest) > 1:
                lines = '@(Get-Content -LiteralPath ' + self.paths(rest[1:]) + ' -Encoding UTF8)'
            elif not in_pipeline:
                raise Unsupported('grep 需要文件名或文本管道输入。')
            else:
                lines = '$b2psInput'
            return f'Invoke-B2PSGrep -Lines {lines} -Pattern {pattern}' + ''.join(' ' + option for flag, option in [('-F', '-Fixed'), ('-i', '-IgnoreCase'), ('-v', '-Invert')] if flag in flags)
        if name in {'head', 'tail'}:
            count = 10
            if args and re.fullmatch('-[0-9]+', args[0].raw):
                count, args = int(args[0].raw[1:]), args[1:]
            elif args and args[0].raw == '-n':
                if len(args) < 2 or not args[1].raw.isdigit():
                    raise Unsupported('head/tail -n 需要非负整数。')
                count, args = int(args[1].raw), args[2:]
            _, paths = self.options(args, set())
            prefix = 'Get-Content -LiteralPath ' + self.paths(paths) + ' -Encoding UTF8 | ' if paths else ''
            if not paths and not in_pipeline:
                raise Unsupported('head/tail 需要文件名或文本管道输入。')
            if len(paths) > 1:
                raise Unsupported('head/tail 多文件模式的标题和计数语义暂不支持。')
            return prefix + f'Select-Object -{"First" if name == "head" else "Last"} {count}'
        if name == 'wc':
            if not args or args[0].raw != '-l':
                raise Unsupported('wc 只支持 -l 行数统计。')
            if len(args) > 1:
                if len(args) != 2:
                    raise Unsupported('wc -l 只支持一个文件。')
                self.warn(tokens[0].line, 'wc -l 按文本行统计；末尾无换行的文件可能与 Bash 结果不同。')
                return '(Get-Content -LiteralPath ' + self.word(args[1]) + ' -Encoding UTF8 | Measure-Object).Count'
            if not in_pipeline:
                raise Unsupported('wc -l 需要文件名或文本管道输入。')
            return 'Measure-Object | Select-Object -ExpandProperty Count'
        if in_pipeline:
            raise Unsupported('含外部程序的管道暂不支持：字节流与退出码不能可靠转换。请拆成独立步骤。')
        if not dynamic and name in {'python3', 'pip3'}:
            self.warn(tokens[0].line, f'{name} 按 Windows 常用名称改为 {name[:-1]}，请核对版本。')
            name = name[:-1]
        if dynamic:
            self.warn(tokens[0].line, '变量指定的程序按独立可执行文件调用；Windows 上 python3/pip3 使用 python/pip。')
        elif '/' in name or '\\' in name:
            if not name.lower().endswith(('.exe', '.cmd', '.bat')):
                raise Unsupported('路径形式的外部程序需明确为 .exe/.cmd/.bat；.sh 不能直接转换为 Windows 程序。')
        elif name not in self.NATIVE:
            self.warn(tokens[0].line, f'外部命令 {name} 保留调用；需在 Windows 安装同名程序。')
        if name:
            self.dependencies.add(name)
        if name in {'curl', 'wget', 'make', 'tar'}:
            self.warn(tokens[0].line, f'{name} 调用真实外部程序；Windows 版本的选项、路径和可用性需检查。')
        argument_expressions = [self.word(t) for t in args]
        if name in {'npm', 'npx', 'code'} or name.lower().endswith(('.cmd', '.bat')):
            if any(re.search('["%!\r\n]', expr[1:-1]) for expr in argument_expressions if expr.startswith("'")):
                raise Unsupported('Windows 批处理程序参数中的双引号、% 或 ! 需要人工处理。')
        return 'Invoke-B2PSNative -Name ' + (name_expression if dynamic else ps_quote(name)) + ' -ArgumentList @(' + ', '.join(argument_expressions) + ')'

    def assignment(self, name: str, value: Token, export: bool = False) -> str:
        if name.upper() == 'PATH':
            raise Unsupported('PATH 的 Unix 路径和冒号分隔符不能可靠映射到 Windows；请人工改写。')
        if name == 'PWD':
            raise Unsupported('PWD 与当前目录关联，不能作为普通变量赋值。')
        if export:
            other = self.export_names.get(name.upper())
            if other and other != name:
                raise Unsupported('Windows 环境变量名称不区分大小写，不能同时导出仅大小写不同的变量。')
            self.export_names[name.upper()] = name
        return f'Set-B2PSValue {ps_quote(name)} {self.word(value, expansion=True)}' + (' -Export' if export else '')

    def printf_expression(self, args: list[Token]) -> str:
        if not args:
            raise Unsupported('printf 缺少格式字符串。')
        fmt = self.literal(args[0])
        if re.search(r'%(?![sdi%])', re.sub(r'%%', '', fmt)) or re.search(r'\\(?![nrt\\])', fmt):
            raise Unsupported('printf 支持 %s/%d/%i/%% 和 \\n/\\r/\\t/\\\\；其他格式需人工检查。')
        return 'Format-B2PSPrintf -Format ' + ps_quote(fmt) + ' -Values @(' + ', '.join(self.word(t) for t in args[1:]) + ')'

    def find_command(self, args: list[Token]) -> str:
        if not args or args[0].raw.startswith('-'):
            raise Unsupported('find 需要一个搜索路径。')
        code = 'Find-B2PSPath -Path ' + self.word(args[0])
        index = 1
        while index < len(args):
            flag = args[index].raw
            if index + 1 >= len(args) or flag not in {'-mindepth', '-maxdepth', '-type', '-name', '-iname'}:
                raise Unsupported('find 支持单路径及 -mindepth/-maxdepth/-type d或f/-name/-iname；其他表达式需人工检查。')
            value = args[index + 1]
            if flag in {'-mindepth', '-maxdepth'}:
                if not value.raw.isdigit() or int(value.raw) > 2147483647:
                    raise Unsupported('find 深度需要非负整数。')
                code += (' -MinDepth ' if flag == '-mindepth' else ' -MaxDepth ') + value.raw
            elif flag == '-type':
                if value.raw not in {'d', 'f'}:
                    raise Unsupported('find -type 支持 d（目录）和 f（文件）。')
                code += ' -Type ' + ps_quote(value.raw)
            else:
                code += ' -Pattern ' + self.word(value) + (' -IgnoreCase' if flag == '-iname' else '')
            index += 2
        self.warn(args[0].line, 'find 输出 Windows 绝对路径，按名称排序；不会遍历目录链接。')
        return code

    def script_command(self, name: str, args: list[Token], line: int) -> str:
        if not args or args[0].raw.startswith('-'):
            raise Unsupported(f'{name} 需要脚本路径；不支持 -c 等动态 Shell 代码。')
        path_text = self.literal(args[0])
        if name in {'.', 'source'} and Path(path_text).suffix.lower() not in {'.sh', '.bash'}:
            if len(args) != 1:
                raise Unsupported('环境文件加载不支持位置参数。')
            self.warn(line, '环境文件在运行时按 NAME=value 读取，支持引号、普通变量和 export；含其他 Shell 代码时会明确报错。')
            return 'Import-B2PSEnv -Path ' + self.word(args[0])
        if not self.source_path:
            raise Unsupported('调用其他 .sh 时请用“打开 .sh 文件”或 CLI 文件入口，让转换器同时读取并打包子脚本。')
        path = Path(path_text)
        candidates = [path] if path.is_absolute() else [parent / path for parent in self.source_path.parents]
        resolved = next((p.resolve() for p in candidates if p.is_file()), None)
        if resolved is None:
            raise Unsupported(f'找不到被调用的脚本 {path_text}；请检查它相对原项目的位置。')
        if resolved in self.active:
            raise Unsupported(f'脚本循环引用：{path_text}。')
        if resolved not in self.bundle:
            child = Translator(resolved, self.bundle, self.active)
            self.active.add(resolved)
            try:
                body = child.body(resolved.read_text(encoding='utf-8-sig'))
            except (OSError, UnicodeError) as error:
                raise Unsupported(f'无法读取子脚本 {path_text}: {error}') from error
            finally:
                self.active.remove(resolved)
            self.bundle[resolved] = body
            self.commands += child.commands
            self.dependencies.update(child.dependencies)
            self.issues.extend(Issue(line, i.level, f'{path_text}:L{i.line}: {i.message}') for i in child.issues)
        return 'Invoke-B2PSScript -Path ' + ps_quote(str(resolved)) + ' -ArgumentList @(' + ', '.join(self.word(t) for t in args[1:]) + ')' + (' -Source' if name != 'bash' else '')

    def condition(self, args: list[Token]) -> str:
        if not args:
            return '$false'
        if args[0].raw == '!':
            return '-not (' + self.condition(args[1:]) + ')'
        if len(args) == 1:
            return '(' + self.word(args[0]) + ").Length -gt 0"
        if len(args) == 2:
            op, value = args[0].raw, self.word(args[1])
            if op in {'-e', '-f', '-d'}:
                return 'Test-Path -LiteralPath ' + value + ({'-f': ' -PathType Leaf', '-d': ' -PathType Container'}.get(op, ''))
            if op in {'-z', '-n'}:
                return '(' + value + ').Length ' + ('-eq' if op == '-z' else '-gt') + ' 0'
        if len(args) == 3:
            left, op, right = self.word(args[0]), args[1].raw, self.word(args[2])
            if op in {'=', '==', '!='}:
                return left + (' -cne ' if op == '!=' else ' -ceq ') + right
            if op in {'-eq', '-ne', '-gt', '-ge', '-lt', '-le'}:
                return f'[long]{left} {op} [long]{right}'
        raise Unsupported('test/[ ] 仅支持简单文件判断、字符串判断和整数比较。')

    def pipeline(self, tokens: list[Token]) -> str:
        redirect = None
        for index, token in enumerate(tokens):
            if token.kind == 'op' and token.raw in {'>', '>>'}:
                if index != len(tokens) - 2 or tokens[-1].kind != 'word':
                    raise Unsupported('文本重定向只支持命令末尾的 > 文件 或 >> 文件。')
                redirect = token.raw, tokens[-1]
                tokens = tokens[:index]
                break
        pieces: list[list[Token]] = [[]]
        for token in tokens:
            if token.kind == 'op' and token.raw == '|':
                pieces.append([])
            else:
                pieces[-1].append(token)
        if any(not p for p in pieces):
            raise Unsupported('管道缺少命令。')
        if len(pieces) == 1:
            code = self.command(pieces[0])
        else:
            stages = []
            for piece in pieces:
                code = self.command(piece, True)
                # grep consumes the input array explicitly; head/tail/wc use the pipeline.
                if piece[0].raw in {'head', 'tail', 'wc'} and 'Get-Content' not in code:
                    code = '@($b2psInput) | ' + code
                stages.append('{ param($b2psInput) ' + code + ' }')
            code = 'Invoke-B2PSPipeline -Stages @(' + ', '.join(stages) + ')'
        if redirect:
            if 'Invoke-B2PSNative' in code:
                raise Unsupported('外部程序的输出重定向需人工检查；下载文件建议 curl -o 文件 URL。')
            self.warn(redirect[1].line, '输出重定向写入 UTF-8 无 BOM 文本，统一使用 LF 换行。')
            append = ' -Append' if redirect[0] == '>>' else ''
            if len(pieces) == 1 and pieces[0][0].raw == 'printf':
                code = 'Write-B2PSFileText -Path ' + self.word(redirect[1]) + ' -Text (' + self.printf_expression(pieces[0][1:]) + ')' + append
            else:
                code = 'Write-B2PSText -Path ' + self.word(redirect[1]) + ' -Lines @(' + code + ')' + append
        return code

    @staticmethod
    def indent(code: str) -> str:
        return '\n'.join('    ' + line for line in code.splitlines())

    def chain(self, tokens: list[Token]) -> str:
        segments: list[list[Token]] = [[]]
        joins: list[str] = []
        for token in tokens:
            if token.kind == 'op' and token.raw in {'&&', '||'}:
                joins.append(token.raw)
                segments.append([])
            else:
                segments[-1].append(token)
        if any(not segment for segment in segments):
            raise Unsupported('&& / || 缺少前后命令。')
        steps = []
        for index, segment in enumerate(segments):
            negate = segment[0].raw == '!'
            if negate:
                segment = segment[1:]
            code = self.pipeline(segment)
            flags = ' -Required' if index == len(segments) - 1 else ''
            flags += f' -Line {segment[0].line}'
            if negate:
                flags += ' -Negate'
            if segment and all(re.match(r'^[A-Za-z_][A-Za-z_0-9]*=', t.raw) for t in segment):
                flags += ' -Assignment'
            step = 'Invoke-B2PSStep {\n' + self.indent(code) + '\n}' + flags
            if index:
                comparison = '-eq' if joins[index - 1] == '&&' else '-ne'
                step = f'if ($script:B2PSStatus {comparison} 0) {{\n' + self.indent(step) + '\n}'
            steps.append(step)
            self.commands += 1
        return '\n'.join(steps)

    def nodes(self, nodes: list[Node]) -> str:
        output = []
        for node in nodes:
            output.append(f'# Bash line {node.line}')
            try:
                if node.kind == 'command':
                    if self.loop_depth and len(node.tokens) == 1 and node.tokens[0].raw in {'break', 'continue'}:
                        output.append(node.tokens[0].raw)
                    else:
                        output.append(self.chain(node.tokens))
                elif node.kind == 'if':
                    for index, (condition, body) in enumerate(node.branches):
                        code = self.nodes(condition)
                        branch = self.nodes(body) or '$script:B2PSStatus = 0'
                        output.append(('if' if index == 0 else 'elseif') + ' (Test-B2PSCondition {\n' + self.indent(code) + '\n}) {\n' + self.indent(branch) + '\n}')
                    otherwise = self.nodes(node.otherwise) or '$script:B2PSStatus = 0'
                    output.append('else {\n' + self.indent(otherwise) + '\n}')
                elif node.kind in {'while', 'until', 'for'}:
                    suffix = f'{node.line}_{self.loop_depth}'
                    result = '$b2psLoopStatus' + suffix
                    output.append(result + ' = 0')
                    if node.kind == 'for':
                        if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', node.variable):
                            raise Unsupported('for 变量名无效。')
                        values = '@(' + ', '.join(self.word(t) for t in node.tokens) + ')'
                        header = f'foreach ($b2psLoopValue{suffix} in {values}) {{'
                        start = f'Set-B2PSValue {ps_quote(node.variable)} $b2psLoopValue{suffix}\n'
                    else:
                        condition = self.nodes(node.condition)
                        header = 'while (' + ('-not ' if node.kind == 'until' else '') + '(Test-B2PSCondition {\n' + self.indent(condition) + '\n})) {'
                        start = ''
                    self.loop_depth += 1
                    try:
                        body = self.nodes(node.body)
                    finally:
                        self.loop_depth -= 1
                    output.append(header + '\n' + self.indent(start + body + '\n' + result + ' = $script:B2PSStatus') + '\n}')
                    output.append('$script:B2PSStatus = ' + result)
            except Unsupported as error:
                self.issues.append(Issue(node.line, 'error', str(error)))
                output.append('# MANUAL REVIEW: ' + str(error).replace('\n', ' '))
        return '\n'.join(output)

    def body(self, source: str) -> str:
        try:
            parser = ShellParser(lex(source.replace('\r\n', '\n').lstrip('\ufeff')))
            body = self.nodes(parser.parse())
            comments = ['# ' + t.raw[1:] for t in parser.comments if not t.raw.startswith('#!')]
            if comments:
                body += '\n# Original comments\n' + '\n'.join(comments)
            return body
        except Unsupported as error:
            match = re.search(r'第 (\d+) 行', str(error))
            self.issues.append(Issue(int(match[1]) if match else 1, 'error', str(error)))
            return '# MANUAL REVIEW: ' + str(error).replace('\n', ' ')

    def translate(self, source: str) -> Result:
        if self.source_path:
            self.active.add(self.source_path)
        try:
            body = self.body(source)
        finally:
            if self.source_path:
                self.active.discard(self.source_path)
        return self.finish([body])

    def finish(self, body: list[str]) -> Result:
        preamble = ['# Bash → PowerShell 转换结果']
        errors = [i for i in self.issues if i.level == 'error']
        for issue in self.issues:
            level = 'ERROR' if issue.level == 'error' else 'WARNING'
            preamble.append(f'# {level} L{issue.line}: {issue.message}')
        if errors:
            preamble.append("throw 'Conversion incomplete: resolve all ERROR diagnostics and reconvert before running.'")
        if self.dependencies:
            preamble.append('# Required external programs: ' + ', '.join(sorted(self.dependencies)))
        config = []
        if self.source_path:
            config.append('$script:B2PSSource = ' + ps_quote(str(self.source_path)))
            config.append('$script:B2PSZero = $script:B2PSSource')
        for path, child_body in self.bundle.items():
            config.append('$script:B2PSScripts[' + ps_quote(str(path)) + '] = {\n' + self.indent(child_body) + '\n}')
        script = '\n'.join(preamble) + '\n\n' + HEADER + '\n' + '\n'.join(config) + '\n# Main script\n' + '\n\n'.join(body) + '\n'
        return Result(script, self.issues, self.commands)


def convert(source: str, source_path: Path | str | None = None) -> Result:
    return Translator(Path(source_path) if source_path else None).translate(source.replace('\r\n', '\n').lstrip('\ufeff'))


def convert_file(path: Path | str) -> Result:
    path = Path(path).resolve()
    return convert(path.read_text(encoding="utf-8-sig"), path)
