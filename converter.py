"""A conservative Bash-step translator. Conversion never executes input."""
from __future__ import annotations

from dataclasses import dataclass, field
import re
from pathlib import Path

from shellsyntax import Token, Unsupported, Node, ShellParser, lex, expansion_end
from psruntime import EXTENDED_RUNTIME


@dataclass(frozen=True)
class Issue:
    line: int
    level: str
    message: str


@dataclass
class Result:
    script: str
    issues: list[Issue] = field(default_factory=list)
    commands: int = 0

    @property
    def errors(self) -> list[Issue]:
        return [i for i in self.issues if i.level == 'error']

    @property
    def warnings(self) -> list[Issue]:
        return [i for i in self.issues if i.level == 'warning']


def ps_quote(value: str) -> str:
    if '\n' in value or '\r' in value:
        escaped = value.replace('`', '``').replace('$', '`$').replace('"', '`"').replace('\r', '`r').replace('\n', '`n')
        return '"' + escaped + '"'
    return "'" + value.replace("'", "''") + "'"


HEADER = r'''# Generated by Bash → PowerShell. Compatible with Windows PowerShell 5.1 / PowerShell 7.
# Review the diagnostics before running. No input is executed during conversion.
$script:B2PSVars = [System.Collections.Generic.Dictionary[string,string]]::new([StringComparer]::Ordinal)
$script:B2PSExported = [System.Collections.Generic.Dictionary[string,bool]]::new([StringComparer]::Ordinal)
$script:B2PSStatus = 0
$script:B2PSErrexit = $false
$script:B2PSUnset = $false

function Get-B2PSValue([string] $Name) {
    if ($Name -eq '?') { return [string]$script:B2PSStatus }
    if ($Name -eq '0') { return $script:B2PSZero }
    if ($Name -eq 'BASH_SOURCE') { return $script:B2PSSource }
    if ($Name -eq '#') { return [string]$script:B2PSArgs.Count }
    if ($Name -match '^\d+$') {
        $index = [int]$Name - 1
        if ($index -ge 0 -and $index -lt $script:B2PSArgs.Count) { return [string]$script:B2PSArgs[$index] }
        if ($script:B2PSUnset) { Stop-B2PSFatal "Unset Bash argument: $Name" }
        return ''
    }
    if ($script:B2PSVars.ContainsKey($Name)) { return [string]$script:B2PSVars[$Name] }
    if ($Name -eq 'HOME') { return [Environment]::GetFolderPath('UserProfile') }
    if ($Name -eq 'PWD') { return (Get-Location).Path }
    $value = [Environment]::GetEnvironmentVariable($Name, 'Process')
    if ($null -eq $value -and $script:B2PSUnset) { Stop-B2PSFatal "Unset Bash variable: $Name" }
    return [string]$value
}
function Set-B2PSValue([string] $Name, [string] $Value, [switch] $Export) {
    $script:B2PSVars[$Name] = $Value
    if ($Export -or $script:B2PSAllExport) { $script:B2PSExported[$Name] = $true }
    if ($script:B2PSExported.ContainsKey($Name)) {
        [Environment]::SetEnvironmentVariable($Name, $Value, 'Process')
    }
}
function Invoke-B2PSNative([string] $Name, [string[]] $ArgumentList = @()) {
    if ($env:OS -eq 'Windows_NT' -and $Name -eq 'python3') { $Name = 'python' }
    if ($env:OS -eq 'Windows_NT' -and $Name -eq 'pip3') { $Name = 'pip' }
    $command = Get-Command -Name $Name -CommandType Application -ErrorAction Stop | Select-Object -First 1
    $global:LASTEXITCODE = 0
    $PSNativeCommandUseErrorActionPreference = $false
    $PSNativeCommandArgumentPassing = 'Legacy'
    $b2psIsBatch = [IO.Path]::GetExtension($command.Source) -in @('.cmd', '.bat')
    $b2psArguments = @()
    foreach ($value in $ArgumentList) {
        if ($b2psIsBatch -and $value -match '["%!\r\n]') {
            throw 'A .cmd/.bat argument contains quoting or expansion characters that require manual review.'
        }
        # Encode Windows argv ourselves, including empty strings and embedded quotes.
        $encoded = [regex]::Replace([string]$value, '(\\*)"', '$1$1\"')
        $encoded = [regex]::Replace($encoded, '(\\+)$', '$1$1')
        $b2psArguments += '"' + $encoded + '"'
    }
    & $command.Source @b2psArguments
    $b2psExitCode = $global:LASTEXITCODE
    if ($b2psExitCode -ne 0) {
        $errorObject = New-Object System.Exception("$Name exited with code $b2psExitCode")
        $errorObject.Data['B2PSExitCode'] = $b2psExitCode
        throw $errorObject
    }
}
function Invoke-B2PSStep([scriptblock] $Action, [switch] $Required, [switch] $Negate, [switch] $Assignment, [int] $Line = 0) {
    $ErrorActionPreference = 'Stop'
    $script:B2PSExpansionStatus = $null
    try {
        . $Action
        $script:B2PSStatus = if ($Assignment -and $null -ne $script:B2PSExpansionStatus) { $script:B2PSExpansionStatus } else { 0 }
    } catch {
        if ($_.Exception.Data.Contains('B2PSFatal')) { throw }
        $script:B2PSStatus = 1
        if ($_.Exception.Data.Contains('B2PSExitCode')) {
            $script:B2PSStatus = [int]$_.Exception.Data['B2PSExitCode']
        } else {
            Write-Warning $_.Exception.Message
        }
    }
    if ($Negate) { $script:B2PSStatus = if ($script:B2PSStatus -eq 0) { 1 } else { 0 } }
    elseif ($Required -and $script:B2PSErrexit -and $script:B2PSGuardDepth -eq 0 -and $script:B2PSStatus -ne 0) {
        $errorObject = New-Object System.Exception("Bash line ${Line}: step failed with code $script:B2PSStatus")
        $errorObject.Data['B2PSExitCode'] = $script:B2PSStatus
        throw $errorObject
    }
}
function Assert-B2PSTest([bool] $Condition) {
    if (-not $Condition) {
        $errorObject = New-Object System.Exception('Bash test returned false')
        $errorObject.Data['B2PSExitCode'] = 1
        throw $errorObject
    }
}
function Update-B2PSFile([string[]] $Paths) {
    foreach ($item in $Paths) {
        if (Test-Path -LiteralPath $item -PathType Container) { (Get-Item -LiteralPath $item).LastWriteTime = Get-Date }
        elseif (Test-Path -LiteralPath $item) { (Get-Item -LiteralPath $item).LastWriteTime = Get-Date }
        else { [IO.File]::WriteAllBytes($ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($item), [byte[]]@()) }
    }
}
function Write-B2PSText([string] $Path, [object[]] $Lines, [switch] $Append) {
    $text = if ($Lines.Count) { (($Lines | ForEach-Object { [string]$_ }) -join "`n") + "`n" } else { '' }
    $encoding = New-Object System.Text.UTF8Encoding($false)
    $resolved = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Path)
    if ($Append) { [IO.File]::AppendAllText($resolved, $text, $encoding) }
    else { [IO.File]::WriteAllText($resolved, $text, $encoding) }
}
'''


