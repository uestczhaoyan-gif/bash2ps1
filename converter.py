"""A conservative Bash-step translator. Conversion never executes input."""
from __future__ import annotations

from dataclasses import dataclass, field
import re


@dataclass(frozen=True)
class Issue:
    line: int
    level: str
    message: str


@dataclass
class Result:
    script: str
    issues: list[Issue] = field(default_factory=list)
    commands: int = 0

    @property
    def errors(self) -> list[Issue]:
        return [i for i in self.issues if i.level == 'error']

    @property
    def warnings(self) -> list[Issue]:
        return [i for i in self.issues if i.level == 'warning']


@dataclass(frozen=True)
class Token:
    raw: str
    line: int
    kind: str = 'word'


class Unsupported(ValueError):
    pass


def ps_quote(value: str) -> str:
    if '\n' in value or '\r' in value:
        escaped = value.replace('`', '``').replace('$', '`$').replace('"', '`"').replace('\r', '`r').replace('\n', '`n')
        return '"' + escaped + '"'
    return "'" + value.replace("'", "''") + "'"


def lex(source: str) -> list[Token]:
    """Keep shell quoting; operators inside strings are never split."""
    tokens: list[Token] = []
    i, line = 0, 1
    operators = ('&&', '||', '>>', '<<', '2>&1', '2>>', '2>', '|', ';', '>', '<', '&', '(', ')')
    while i < len(source):
        c = source[i]
        if c in ' \t\r':
            i += 1
            continue
        if source.startswith('\\\n', i) or source.startswith('\\\r\n', i):
            i += 3 if source.startswith('\\\r\n', i) else 2
            line += 1
            continue
        if c == '\n':
            tokens.append(Token('\n', line, 'op'))
            line += 1
            i += 1
            continue
        if c == '#':
            end = source.find('\n', i)
            end = len(source) if end < 0 else end
            tokens.append(Token(source[i:end], line, 'comment'))
            i = end
            continue
        op = next((o for o in operators if source.startswith(o, i)), None)
        if op:
            tokens.append(Token(op, line, 'op'))
            i += len(op)
            continue
        start, start_line, quote = i, line, None
        while i < len(source):
            c = source[i]
            if c == '\\' and quote != "'":
                if i + 1 == len(source):
                    raise Unsupported(f'第 {line} 行：末尾反斜杠缺少续行内容。')
                if source[i + 1] == '\n':
                    line += 1
                elif source.startswith('\\\r\n', i):
                    line += 1
                    i += 1
                i += 2
                continue
            if quote:
                if c == quote:
                    quote = None
                if c == '\n':
                    line += 1
                i += 1
                continue
            if c in "'\"":
                quote = c
                i += 1
                continue
            if source.startswith('${', i):
                end = source.find('}', i + 2)
                if end < 0:
                    raise Unsupported(f'第 {line} 行：变量表达式缺少右花括号。')
                line += source[i:end + 1].count('\n')
                i = end + 1
                continue
            if c in ' \t\r\n' or any(source.startswith(o, i) for o in operators):
                break
            i += 1
        if quote:
            raise Unsupported(f'第 {start_line} 行：引号没有闭合。')
        tokens.append(Token(source[start:i], start_line))
    return tokens


HEADER = r'''# Generated by Bash → PowerShell. Compatible with Windows PowerShell 5.1 / PowerShell 7.
# Review the diagnostics before running. No input is executed during conversion.
$script:B2PSVars = [System.Collections.Generic.Dictionary[string,string]]::new([StringComparer]::Ordinal)
$script:B2PSExported = [System.Collections.Generic.Dictionary[string,bool]]::new([StringComparer]::Ordinal)
$script:B2PSStatus = 0
$script:B2PSErrexit = $false
$script:B2PSUnset = $false

function Get-B2PSValue([string] $Name) {
    if ($Name -eq '?') { return [string]$script:B2PSStatus }
    if ($script:B2PSVars.ContainsKey($Name)) { return [string]$script:B2PSVars[$Name] }
    if ($Name -eq 'HOME') { return [Environment]::GetFolderPath('UserProfile') }
    if ($Name -eq 'PWD') { return (Get-Location).Path }
    $value = [Environment]::GetEnvironmentVariable($Name, 'Process')
    if ($null -eq $value -and $script:B2PSUnset) { throw "Unset Bash variable: $Name" }
    return [string]$value
}
function Set-B2PSValue([string] $Name, [string] $Value, [switch] $Export) {
    $script:B2PSVars[$Name] = $Value
    if ($Export) { $script:B2PSExported[$Name] = $true }
    if ($script:B2PSExported.ContainsKey($Name)) {
        [Environment]::SetEnvironmentVariable($Name, $Value, 'Process')
    }
}
function Invoke-B2PSNative([string] $Name, [string[]] $ArgumentList = @()) {
    $command = Get-Command -Name $Name -CommandType Application -ErrorAction Stop | Select-Object -First 1
    $global:LASTEXITCODE = 0
    $PSNativeCommandUseErrorActionPreference = $false
    $PSNativeCommandArgumentPassing = 'Legacy'
    $b2psIsBatch = [IO.Path]::GetExtension($command.Source) -in @('.cmd', '.bat')
    $b2psArguments = @()
    foreach ($value in $ArgumentList) {
        if ($b2psIsBatch -and $value -match '["%!\r\n]') {
            throw 'A .cmd/.bat argument contains quoting or expansion characters that require manual review.'
        }
        # Encode Windows argv ourselves, including empty strings and embedded quotes.
        $encoded = [regex]::Replace([string]$value, '(\\*)"', '$1$1\"')
        $encoded = [regex]::Replace($encoded, '(\\+)$', '$1$1')
        $b2psArguments += '"' + $encoded + '"'
    }
    & $command.Source @b2psArguments
    $b2psExitCode = $global:LASTEXITCODE
    if ($b2psExitCode -ne 0) {
        $errorObject = New-Object System.Exception("$Name exited with code $b2psExitCode")
        $errorObject.Data['B2PSExitCode'] = $b2psExitCode
        throw $errorObject
    }
}
function Invoke-B2PSStep([scriptblock] $Action, [switch] $Required) {
    $ErrorActionPreference = 'Stop'
    try {
        . $Action
        $script:B2PSStatus = 0
    } catch {
        $script:B2PSStatus = 1
        if ($_.Exception.Data.Contains('B2PSExitCode')) {
            $script:B2PSStatus = [int]$_.Exception.Data['B2PSExitCode']
        } else {
            Write-Warning $_.Exception.Message
        }
        if ($Required -and $script:B2PSErrexit) { throw }
    }
}
function Assert-B2PSTest([bool] $Condition) {
    if (-not $Condition) {
        $errorObject = New-Object System.Exception('Bash test returned false')
        $errorObject.Data['B2PSExitCode'] = 1
        throw $errorObject
    }
}
function Update-B2PSFile([string[]] $Paths) {
    foreach ($item in $Paths) {
        if (Test-Path -LiteralPath $item -PathType Container) { (Get-Item -LiteralPath $item).LastWriteTime = Get-Date }
        elseif (Test-Path -LiteralPath $item) { (Get-Item -LiteralPath $item).LastWriteTime = Get-Date }
        else { [IO.File]::WriteAllBytes($ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($item), [byte[]]@()) }
    }
}
function Write-B2PSText([string] $Path, [object[]] $Lines, [switch] $Append) {
    $text = if ($Lines.Count) { (($Lines | ForEach-Object { [string]$_ }) -join "`n") + "`n" } else { '' }
    $encoding = New-Object System.Text.UTF8Encoding($false)
    $resolved = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Path)
    if ($Append) { [IO.File]::AppendAllText($resolved, $text, $encoding) }
    else { [IO.File]::WriteAllText($resolved, $text, $encoding) }
}
'''


class Translator:
    BLOCKED = {'if', 'then', 'elif', 'else', 'fi', 'for', 'while', 'until', 'do', 'done',
               'case', 'esac', 'function', 'select', 'eval', 'exec', 'source', '.', 'bash',
               'sh', 'zsh', 'sudo', 'su', 'apt', 'apt-get', 'yum', 'dnf', 'pacman',
               'chmod', 'chown', 'ln', 'sed', 'awk', 'find', 'xargs', 'read', 'trap',
               'return', 'break', 'continue', 'exit', 'pushd', 'popd', 'alias', 'unalias'}
    NATIVE = {'git', 'python', 'python3', 'pip', 'pip3', 'node', 'npm', 'npx', 'docker',
              'go', 'cargo', 'rustc', 'cmake', 'dotnet', 'java', 'javac', 'ffmpeg', 'tar',
              'curl', 'wget', 'make', 'code'}
    def __init__(self):
        self.issues: list[Issue] = []
        self.commands = 0
        self.dependencies: set[str] = set()
        self.export_names: dict[str, str] = {}

    def warn(self, line: int, message: str):
        issue = Issue(line, 'warning', message)
        if issue not in self.issues:
            self.issues.append(issue)

    def word(self, token: Token) -> str:
        raw, i, quote = token.raw, 0, None
        chunks: list[str] = []
        literal: list[str] = []
        def flush():
            if literal:
                chunks.append(ps_quote(''.join(literal)))
                literal.clear()
        if raw.startswith('~'):
            if raw == '~' or raw.startswith('~/'):
                chunks.append("(Get-B2PSValue 'HOME')")
                i = 1
            else:
                raise Unsupported('不支持 ~用户名 路径；请使用明确的 Windows 路径。')
        while i < len(raw):
            c = raw[i]
            if c == '\\' and quote != "'":
                if raw.startswith('\\\r\n', i):
                    i += 3
                    continue
                n = raw[i + 1]
                if n == '\n':
                    i += 2
                    continue
                if quote == '"' and n not in '$`"\\':
                    literal.append('\\')
                    i += 1
                else:
                    literal.append(n)
                    i += 2
                continue
            if quote == "'":
                if c == "'":
                    quote = None
                else:
                    literal.append(c)
                i += 1
                continue
            if c in "'\"" and (quote is None or quote == c):
                quote = None if quote == c else c
                i += 1
                continue
            if c == '`':
                raise Unsupported('反引号命令替换需要人工改写，不能按 PowerShell 转义符处理。')
            if c == '$':
                if raw.startswith('$(', i) or (i + 1 < len(raw) and raw[i + 1] in "'\""):
                    raise Unsupported('命令替换 / 算术展开 / ANSI-C 引号暂不支持。')
                match = re.match(r'\$(?:\{([A-Za-z_][A-Za-z_0-9]*|\?)\}|([A-Za-z_][A-Za-z_0-9]*|\?))', raw[i:])
                if match:
                    name = match.group(1) or match.group(2)
                    flush()
                    chunks.append(f'(Get-B2PSValue {ps_quote(name)})')
                    if quote is None:
                        self.warn(token.line, '未加引号的变量按单个字符串传递；Bash 的单词拆分和通配符展开需人工检查。')
                    i += len(match.group(0))
                    continue
                if i + 1 < len(raw) and (raw[i + 1].isdigit() or raw[i + 1] in '{@*#!-'):
                    raise Unsupported('复杂参数展开或位置参数暂不支持；请先改成普通变量。')
            if quote is None and c in '*?[]{}':
                raise Unsupported('未加引号的通配符或花括号展开需人工改写，避免误处理文件。')
            literal.append(c)
            i += 1
        flush()
        if not chunks:
            return "''"
        return chunks[0] if len(chunks) == 1 else '(' + ' + '.join(chunks) + ')'

    def literal(self, token: Token) -> str:
        value = self.word(token)
        if not (value.startswith("'") and value.endswith("'")):
            raise Unsupported('命令名或选项需要是固定文本。')
        return value[1:-1].replace("''", "'")

    def paths(self, tokens: list[Token]) -> str:
        if not tokens:
            raise Unsupported('缺少路径参数。')
        return '@(' + ', '.join(self.word(t) for t in tokens) + ')'

    def options(self, tokens: list[Token], allowed: set[str]) -> tuple[set[str], list[Token]]:
        options, values, ended = set(), [], False
        for token in tokens:
            try:
                candidate = self.literal(token)
            except Unsupported:
                candidate = None
            if not ended and candidate == '--':
                ended = True
                continue
            if not ended and candidate and candidate.startswith('-') and candidate != '-':
                flag = candidate
                if flag.startswith('--'):
                    if flag not in allowed:
                        raise Unsupported(f'不支持选项 {flag}。')
                    options.add(flag)
                else:
                    for c in flag[1:]:
                        if '-' + c not in allowed:
                            raise Unsupported(f'不支持选项 -{c}。')
                        options.add('-' + c)
            else:
                values.append(token)
        return options, values

    def command(self, tokens: list[Token], in_pipeline: bool = False) -> str:
        if not tokens:
            raise Unsupported('缺少命令。')
        if any(t.kind != 'word' for t in tokens):
            raise Unsupported('暂不支持该 Bash 操作符（后台、子 Shell、输入/错误重定向或 here-document）。')
        assignments: list[tuple[str, Token]] = []
        while tokens and (match := re.match(r'^([A-Za-z_][A-Za-z_0-9]*)=(.*)$', tokens[0].raw, re.S)):
            assignments.append((match.group(1), Token(match.group(2), tokens[0].line)))
            tokens = tokens[1:]
        if assignments:
            if in_pipeline:
                raise Unsupported('管道中的变量赋值暂不支持。')
            if not tokens:
                return '; '.join(self.assignment(n, v) for n, v in assignments)
            code = self.command(tokens)
            if any(re.search(r'(?<!\\)\$', t.raw) for t in tokens):
                raise Unsupported('临时环境变量命令同时引用变量时，展开顺序需人工改写。')
            if len({n.lower() for n, _ in assignments}) != len(assignments):
                raise Unsupported('临时环境变量名称重复或大小写冲突。')
            saved, changes, restore = [], [], []
            for number, (name, value) in enumerate(assignments):
                if name.upper() == 'PATH':
                    raise Unsupported('临时 PATH 赋值需按 Windows 路径和分号分隔符人工改写。')
                key = ps_quote(name)
                saved.append(f"$b2psSaved{number} = [Environment]::GetEnvironmentVariable({key}, 'Process')")
                changes.append(f"[Environment]::SetEnvironmentVariable({key}, {self.word(value)}, 'Process')")
                restore.append(f"[Environment]::SetEnvironmentVariable({key}, $b2psSaved{number}, 'Process')")
            self.warn(tokens[0].line, '命令前的临时变量会仅在该命令期间写入进程环境，然后恢复。')
            return '; '.join(saved) + '; try { ' + '; '.join(changes) + '; ' + code + ' } finally { ' + '; '.join(restore) + ' }'
        name = tokens[0].raw if tokens[0].raw in {'[', '[[', ']]', '{', '}'} else self.literal(tokens[0])
        args = tokens[1:]
        if in_pipeline and name not in {'echo', 'printf', 'cat', 'grep', 'head', 'tail', 'wc'}:
            raise Unsupported('管道仅支持 echo/printf/cat/grep/head/tail/wc 的文本组合。')
        if name in self.BLOCKED or name in {'{', '}', '[[', ']]', '!'}:
            raise Unsupported(f'{name} 依赖 Bash 控制结构或 Unix 工具，需要人工改写。')
        if name == 'export':
            if not args:
                raise Unsupported('export 需要变量名或赋值。')
            values = []
            for arg in args:
                match = re.fullmatch(r'([A-Za-z_][A-Za-z_0-9]*)(?:=(.*))?', arg.raw, re.S)
                if not match:
                    raise Unsupported('export 只支持普通变量名或 NAME=value。')
                variable, value = match.groups()
                values.append(self.assignment(variable, Token(value if value is not None else '"${' + variable + '}"', arg.line), True))
            return '; '.join(values)
        if name == 'unset':
            if not args or any(not re.fullmatch('[A-Za-z_][A-Za-z_0-9]*', t.raw) for t in args):
                raise Unsupported('unset 只支持普通变量名。')
            return '; '.join(f"$null = $script:B2PSVars.Remove({ps_quote(t.raw)}); $null = $script:B2PSExported.Remove({ps_quote(t.raw)}); [Environment]::SetEnvironmentVariable({ps_quote(t.raw)}, $null, 'Process')" for t in args)
        if name == 'set':
            values = []
            for arg in args:
                if not re.fullmatch('[-+][eu]+', arg.raw):
                    raise Unsupported('set 仅支持 -e / -u / +e / +u；pipefail 和其他模式需人工检查。')
                for c in arg.raw[1:]:
                    flag = 'Errexit' if c == 'e' else 'Unset'
                    values.append(f"$script:B2PS{flag} = ${'true' if arg.raw[0] == '-' else 'false'}")
            if not values:
                raise Unsupported('不支持无参数的 set。')
            return '; '.join(values)
        if name in {'true', ':'} and not args:
            return '$null = $null'
        if name == 'false' and not args:
            return 'Assert-B2PSTest $false'
        if name in {'test', '['}:
            if name == '[':
                if not args or args[-1].raw != ']':
                    raise Unsupported('[ 条件缺少 ]。')
                args = args[:-1]
            return 'Assert-B2PSTest (' + self.condition(args) + ')'
        if name == 'echo':
            if args and re.fullmatch(r'-[neE]+', args[0].raw):
                raise Unsupported('echo 的 -n/-e/-E 选项需人工改写。')
            return "Write-Output ((@(" + ', '.join(self.word(t) for t in args) + ")) -join ' ')"
        if name == 'printf':
            if not args or self.literal(args[0]) != '%s\\n':
                raise Unsupported('printf 目前只支持 printf \'%s\\n\' 参数...。')
            return 'Write-Output ' + (self.paths(args[1:]) if args[1:] else "''")
        if name == 'pwd' and not args:
            return '(Get-Location).Path'
        if name == 'cd':
            if len(args) > 1 or (args and args[0].raw.startswith('-')):
                raise Unsupported('cd 只支持一个普通路径；cd - 需人工改写。')
            path = self.word(args[0]) if args else "(Get-B2PSValue 'HOME')"
            return 'Set-Location -LiteralPath ' + path
        if name == 'mkdir':
            flags, paths = self.options(args, {'-p', '--parents'})
            values = self.paths(paths)
            return (f'foreach ($b2psPath in {values}) {{ '
                    + ("if (Test-Path -LiteralPath $b2psPath -PathType Container) { continue }; " if flags else '')
                    + "New-Item -ItemType Directory -Path $b2psPath | Out-Null }")
        if name == 'touch':
            _, paths = self.options(args, set())
            return 'Update-B2PSFile -Paths ' + self.paths(paths)
        if name in {'cp', 'mv', 'rm'}:
            allowed = {'-r', '-R', '-f', '--recursive', '--force'} if name != 'mv' else {'-f', '--force'}
            flags, paths = self.options(args, allowed)
            force = ' -Force' if flags & {'-f', '--force'} else ''
            recurse = ' -Recurse' if flags & {'-r', '-R', '--recursive'} else ''
            if name == 'rm':
                values = self.paths(paths)
                self.warn(tokens[0].line, 'rm 会删除文件；运行前核对目标路径。')
                action = f'Remove-Item -LiteralPath $b2psPath{recurse}{force}'
                if force:
                    action = 'if (Test-Path -LiteralPath $b2psPath) { ' + action + ' }'
                return f'foreach ($b2psPath in {values}) {{ {action} }}'
            if len(paths) < 2:
                raise Unsupported(f'{name} 需要来源和目标路径。')
            if recurse:
                self.warn(tokens[0].line, '递归复制目录的覆盖和嵌套行为需检查目标目录。')
            self.warn(tokens[0].line, f'{name} 的已有目标目录和覆盖行为可能与 Unix 有差异，请核对。')
            command = 'Copy-Item' if name == 'cp' else 'Move-Item'
            return f'{command} -LiteralPath {self.paths(paths[:-1])} -Destination {self.word(paths[-1])}{recurse}{force}'
        if name == 'cat':
            if not args:
                raise Unsupported('cat 从标准输入读取需人工改写。')
            _, paths = self.options(args, set())
            self.warn(tokens[0].line, 'cat 按 UTF-8 文本行读取；二进制文件和字节完全一致的复制不适用。')
            return 'Get-Content -LiteralPath ' + self.paths(paths) + ' -Encoding UTF8'
        if name == 'ls':
            flags, paths = self.options(args, {'-a', '-A', '-l', '-h'})
            self.warn(tokens[0].line, 'ls 输出 PowerShell 文件对象，显示格式与 Bash 不同。')
            return 'Get-ChildItem' + (' -LiteralPath ' + self.paths(paths) if paths else '') + (' -Force' if flags & {'-a', '-A'} else '')
        if name == 'grep':
            flags, rest = self.options(args, {'-i', '-v', '-F', '-n'})
            if not rest:
                raise Unsupported('grep 缺少模式。')
            if '-n' in flags:
                raise Unsupported('grep -n 的文件/行号输出格式暂不支持。')
            if '-F' not in flags:
                self.warn(tokens[0].line, 'grep 使用 .NET 正则，复杂的 Bash BRE/ERE 模式需人工检查；固定文本建议 grep -F。')
            pattern = self.word(rest[0])
            compare = '-like' if '-F' in flags else '-match'
            if '-F' in flags:
                expression = f'([string]$_).Contains([string]{pattern})'
                if '-i' in flags:
                    expression = f'([string]$_).IndexOf([string]{pattern}, [StringComparison]::OrdinalIgnoreCase) -ge 0'
            else:
                compare = '-match' if '-i' in flags else '-cmatch'
                expression = f'[string]$_ {compare} {pattern}'
            if '-v' in flags:
                expression = '-not (' + expression + ')'
            filter_code = 'Where-Object { ' + expression + ' }'
            if len(rest) > 1:
                filter_code = 'Get-Content -LiteralPath ' + self.paths(rest[1:]) + ' -Encoding UTF8 | ' + filter_code
            elif not in_pipeline:
                raise Unsupported('grep 需要文件名或文本管道输入。')
            self.warn(tokens[0].line, 'grep 只转换文本过滤；无匹配时的 Bash 退出码 1 不保留。')
            return filter_code
        if name in {'head', 'tail'}:
            count = 10
            if args and re.fullmatch('-[0-9]+', args[0].raw):
                count, args = int(args[0].raw[1:]), args[1:]
            elif args and args[0].raw == '-n':
                if len(args) < 2 or not args[1].raw.isdigit():
                    raise Unsupported('head/tail -n 需要非负整数。')
                count, args = int(args[1].raw), args[2:]
            _, paths = self.options(args, set())
            prefix = 'Get-Content -LiteralPath ' + self.paths(paths) + ' -Encoding UTF8 | ' if paths else ''
            if not paths and not in_pipeline:
                raise Unsupported('head/tail 需要文件名或文本管道输入。')
            if len(paths) > 1:
                raise Unsupported('head/tail 多文件模式的标题和计数语义暂不支持。')
            return prefix + f'Select-Object -{"First" if name == "head" else "Last"} {count}'
        if name == 'wc':
            if not args or args[0].raw != '-l':
                raise Unsupported('wc 只支持 -l 行数统计。')
            if len(args) > 1:
                if len(args) != 2:
                    raise Unsupported('wc -l 只支持一个文件。')
                self.warn(tokens[0].line, 'wc -l 按文本行统计；末尾无换行的文件可能与 Bash 结果不同。')
                return '(Get-Content -LiteralPath ' + self.word(args[1]) + ' -Encoding UTF8 | Measure-Object).Count'
            if not in_pipeline:
                raise Unsupported('wc -l 需要文件名或文本管道输入。')
            return 'Measure-Object | Select-Object -ExpandProperty Count'
        if in_pipeline:
            raise Unsupported('含外部程序的管道暂不支持：字节流与退出码不能可靠转换。请拆成独立步骤。')
        if name in {'python3', 'pip3'}:
            self.warn(tokens[0].line, f'{name} 按 Windows 常用名称改为 {name[:-1]}，请核对版本。')
            name = name[:-1]
        if '/' in name or '\\' in name:
            if not name.lower().endswith(('.exe', '.cmd', '.bat')):
                raise Unsupported('路径形式的外部程序需明确为 .exe/.cmd/.bat；.sh 不能直接转换为 Windows 程序。')
        elif name not in self.NATIVE:
            self.warn(tokens[0].line, f'外部命令 {name} 保留调用；需在 Windows 安装同名程序。')
        self.dependencies.add(name)
        if name in {'curl', 'wget', 'make', 'tar'}:
            self.warn(tokens[0].line, f'{name} 调用真实外部程序；Windows 版本的选项、路径和可用性需检查。')
        argument_expressions = [self.word(t) for t in args]
        if name in {'npm', 'npx', 'code'} or name.lower().endswith(('.cmd', '.bat')):
            if any(re.search('["%!\r\n]', expr[1:-1]) for expr in argument_expressions if expr.startswith("'")):
                raise Unsupported('Windows 批处理程序参数中的双引号、% 或 ! 需要人工处理。')
        return 'Invoke-B2PSNative -Name ' + ps_quote(name) + ' -ArgumentList @(' + ', '.join(argument_expressions) + ')'

    def assignment(self, name: str, value: Token, export: bool = False) -> str:
        if name.upper() == 'PATH':
            raise Unsupported('PATH 的 Unix 路径和冒号分隔符不能可靠映射到 Windows；请人工改写。')
        if name == 'PWD':
            raise Unsupported('PWD 与当前目录关联，不能作为普通变量赋值。')
        if export:
            other = self.export_names.get(name.upper())
            if other and other != name:
                raise Unsupported('Windows 环境变量名称不区分大小写，不能同时导出仅大小写不同的变量。')
            self.export_names[name.upper()] = name
        return f'Set-B2PSValue {ps_quote(name)} {self.word(value)}' + (' -Export' if export else '')

    def condition(self, args: list[Token]) -> str:
        if not args:
            return '$false'
        if args[0].raw == '!':
            return '-not (' + self.condition(args[1:]) + ')'
        if len(args) == 1:
            return '(' + self.word(args[0]) + ").Length -gt 0"
        if len(args) == 2:
            op, value = args[0].raw, self.word(args[1])
            if op in {'-e', '-f', '-d'}:
                return 'Test-Path -LiteralPath ' + value + ({'-f': ' -PathType Leaf', '-d': ' -PathType Container'}.get(op, ''))
            if op in {'-z', '-n'}:
                return '(' + value + ').Length ' + ('-eq' if op == '-z' else '-gt') + ' 0'
        if len(args) == 3:
            left, op, right = self.word(args[0]), args[1].raw, self.word(args[2])
            if op in {'=', '==', '!='}:
                return left + (' -cne ' if op == '!=' else ' -ceq ') + right
            if op in {'-eq', '-ne', '-gt', '-ge', '-lt', '-le'}:
                return f'[long]{left} {op} [long]{right}'
        raise Unsupported('test/[ ] 仅支持简单文件判断、字符串判断和整数比较。')

    def pipeline(self, tokens: list[Token]) -> str:
        redirect = None
        for index, token in enumerate(tokens):
            if token.kind == 'op' and token.raw in {'>', '>>'}:
                if redirect is not None or index != len(tokens) - 2 or tokens[-1].kind != 'word':
                    raise Unsupported('文本重定向只支持命令末尾的 > 文件 或 >> 文件。')
                redirect = token.raw, tokens[-1]
                tokens = tokens[:index]
                break
        pieces: list[list[Token]] = [[]]
        for token in tokens:
            if token.kind == 'op' and token.raw == '|':
                pieces.append([])
            else:
                pieces[-1].append(token)
        if any(not p for p in pieces):
            raise Unsupported('管道缺少命令。')
        code = ' | '.join(self.command(p, len(pieces) > 1) for p in pieces)
        if redirect:
            # Native redirection is byte-sensitive; do not silently convert downloads.
            if 'Invoke-B2PSNative' in code:
                raise Unsupported('外部程序的输出重定向需人工检查；下载文件建议 curl -o 文件 URL。')
            self.warn(redirect[1].line, '输出重定向写入 UTF-8 无 BOM 文本，统一使用 LF 换行。')
            code = 'Write-B2PSText -Path ' + self.word(redirect[1]) + ' -Lines @(' + code + ')' + (' -Append' if redirect[0] == '>>' else '')
        return code

    def translate(self, source: str) -> Result:
        body: list[str] = []
        try:
            tokens = lex(source)
        except Unsupported as error:
            self.issues.append(Issue(1, 'error', str(error)))
            return self.finish(body)
        groups: list[list[Token]] = [[]]
        comments: list[Token] = []
        for token in tokens:
            if token.kind == 'comment':
                comments.append(token)
            elif token.kind == 'op' and token.raw in {'\n', ';'}:
                # A newline after &&, || or | continues the same command list.
                if token.raw == '\n' and groups[-1] and groups[-1][-1].raw in {'&&', '||', '|'}:
                    continue
                groups.append([])
            else:
                groups[-1].append(token)
        for group in groups:
            if not group:
                continue
            first_line = group[0].line
            body.append(f'# Bash line {first_line}')
            segments: list[list[Token]] = [[]]
            joins: list[str] = []
            for token in group:
                if token.kind == 'op' and token.raw in {'&&', '||'}:
                    joins.append(token.raw)
                    segments.append([])
                else:
                    segments[-1].append(token)
            try:
                if any(not s for s in segments):
                    raise Unsupported('&& / || 缺少前后命令。')
                translated = [self.pipeline(s) for s in segments]
                for index, code in enumerate(translated):
                    required = ' -Required' if index == len(translated) - 1 else ''
                    step = 'Invoke-B2PSStep {' + '\n    ' + code + '\n}' + required
                    if index:
                        comparison = '-eq' if joins[index - 1] == '&&' else '-ne'
                        step = f'if ($script:B2PSStatus {comparison} 0) {{\n' + '\n'.join('    ' + l for l in step.splitlines()) + '\n}'
                    body.append(step)
                self.commands += len(translated)
            except Unsupported as error:
                self.issues.append(Issue(first_line, 'error', str(error)))
                body.append('# MANUAL REVIEW: ' + str(error).replace('\n', ' '))
                for s in segments:
                    body.append('# ' + ' '.join(t.raw for t in s).replace('\n', ' '))
        # Keep comments as inert source notes, never as executable content.
        if comments:
            body.append('\n# Original comments')
            body.extend('# ' + c.raw[1:] for c in comments if not c.raw.startswith('#!'))
        return self.finish(body)

    def finish(self, body: list[str]) -> Result:
        preamble = ['# Bash → PowerShell 转换结果']
        errors = [i for i in self.issues if i.level == 'error']
        for issue in self.issues:
            level = 'ERROR' if issue.level == 'error' else 'WARNING'
            preamble.append(f'# {level} L{issue.line}: {issue.message}')
        if errors:
            preamble.append("throw 'Conversion incomplete: resolve all ERROR diagnostics and reconvert before running.'")
        if self.dependencies:
            preamble.append('# Required external programs: ' + ', '.join(sorted(self.dependencies)))
        script = '\n'.join(preamble) + '\n\n' + HEADER + '\n' + '\n\n'.join(body) + '\n'
        return Result(script, self.issues, self.commands)


def convert(source: str) -> Result:
    return Translator().translate(source.replace('\r\n', '\n').lstrip('\ufeff'))
